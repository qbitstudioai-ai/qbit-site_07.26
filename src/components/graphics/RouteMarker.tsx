import styles from "./RouteMarker.module.css";

/**
 * Направление, в которое смотрит вершина треугольника.
 * `right` — переход/маршрут («проблема → результат»), `up` — текущий статус.
 */
export type RouteMarkerDirection = "right" | "up";

interface RouteMarkerProps {
  direction: RouteMarkerDirection;
  /** Дополнительный класс места использования (размер, цвет, отступы). */
  className?: string;
}

/**
 * Функциональный маркер маршрута/статуса (Step 14).
 *
 * Форма выведена из `references/logo/Logo111.svg`: полый треугольник с острыми углами и лёгким
 * наклоном — та же геометрия, что у двух треугольников логотипа. Важная оговорка о происхождении:
 * в файле логотипа НЕТ векторных путей, которые можно было бы переиспользовать напрямую, — это
 * SVG-обёртка вокруг встроенного base64-PNG (~120 КБ растра). Поэтому примитив нарисован заново по
 * форме логотипа, а не извлечён из него. Тащить растр в интерфейс было бы неверно вдвойне: маркер
 * рисуется в размере 10–14px, где растр логотипа превратился бы в грязь, и он обязан
 * перекрашиваться под контекст, чего PNG не умеет.
 *
 * Рукописная неровность штриха логотипа сознательно НЕ воспроизводится: на 10–14px она читается как
 * дефект отрисовки, а не как характер. Взято то, что на малом размере работает и остаётся узнаваемым:
 * контур вместо заливки, острые (miter) углы, наклон.
 *
 * По `docs/02` «Графическая система» такие формы обязаны выполнять функцию, а не украшать. Отсюда
 * два правила, которые не следует менять при доработках:
 * 1. Маркер всегда `aria-hidden`. Он — визуальная половина смысла; вторую половину несёт разметка
 *    (`aria-current` у активного пункта рельса, `aria-pressed` у выбранной боли). Если когда-нибудь
 *    маркер останется единственным носителем состояния, статус пропадёт для скринридера.
 * 2. `currentColor` вместо собственного цвета: маркер наследует цвет контекста, поэтому смысл несёт
 *    ФОРМА и её наличие, а не окраска (`CLAUDE.md`: meaning never relies only on colour).
 */
export function RouteMarker({ direction, className }: RouteMarkerProps) {
  const markerClassName = className ? `${styles.marker} ${className}` : styles.marker;

  // Один и тот же треугольник, повёрнутый под назначение: вершина вправо — переход, вверх — статус.
  // Поворот через SVG-атрибут, а не через CSS transform: так форма остаётся корректной и в тех
  // случаях, когда место использования само что-то трансформирует.
  const rotation = direction === "right" ? 90 : 0;

  return (
    <svg
      className={markerClassName}
      viewBox="0 0 16 16"
      role="presentation"
      aria-hidden="true"
      focusable="false"
    >
      {/* Наклон −6° повторяет посадку треугольников в логотипе: они стоят не строго по осям.
          stroke-linejoin: miter даёт острые углы логотипа (задан в CSS вместе с толщиной). */}
      <g transform={`rotate(${rotation} 8 8)`}>
        <polygon points="8,2.5 14,13.5 2,13.5" transform="rotate(-6 8 8)" />
      </g>
    </svg>
  );
}
