"use client";

import { useEffect, useRef, useState } from "react";
import { officeSceneById, type OfficeSceneId } from "./departmentPhotos";
import { OfficeScenePhoto } from "./OfficePhoto";
import styles from "./SceneCrossfade.module.css";

interface SceneCrossfadeProps {
  /** Какая сцена должна быть показана сейчас. */
  sceneId: OfficeSceneId;
  sizes: string;
  /** Класс фотослоя места использования (геометрия, фильтры, скругление). */
  photoClassName: string;
}

/**
 * Crossfade между сценами отделов (Step 16, OQ-A2-6).
 *
 * Решаемая задача записана как вход этого шага (Step 13, skeptic Phase B, NON-BLOCKING-1):
 * `OfficeScenePhoto` монтируется с `key` по сцене — это обязательно, иначе признак неудачной
 * загрузки «залипает» и один сбой сети гасит фотослой на весь визит. Но следствие в том, что при
 * переключении отдела старый `<img>` размонтируется НЕМЕДЛЕННО, а новый стартует пустым: измерено
 * окно без сцены 73–1261 мс на канале с задержкой 1.2 с (26 из 45 выборок). Пока перехода не было,
 * это было терпимо. Переход, проходящий через пустоту, — не переход.
 *
 * Поэтому во время перехода на экране живут ДВА слоя. Приходящий кладётся поверх и проявляется
 * приближением, а уходящий НЕ гасится по таймеру — он снимается только тогда, когда приходящий
 * сообщил о готовности (`onReady` — успешная загрузка ЛИБО провал). То есть в любой момент виден
 * либо старый кадр, либо новый, но не пустота. Замерено на канале с задержкой 1.2 с: было 16 из 30
 * выборок без видимой сцены, стало 0 из 30.
 *
 * Почему провал тоже считается готовностью: иначе недоступная сцена нового отдела оставила бы на
 * экране сцену предыдущего навсегда — пользователь видел бы чужой отдел и не понял бы, что произошло.
 * При провале приходящий слой — это плейсхолдер Step 8, и он честно занимает своё место.
 */
export function SceneCrossfade({ sceneId, sizes, photoClassName }: SceneCrossfadeProps) {
  // Стек сцен: последняя — текущая, всё, что под ней, — ещё не снятые предыдущие.
  //
  // Глубина стека ограничена сверху ШЕСТЬЮ (overview + пять отделов) и не может расти дальше:
  // добавление происходит только когда сцены в стеке ещё нет, а возврат к уже присутствующей
  // схлопывает стек. При нескольких быстрых переключениях подряд, пока ни одна сцена не догрузилась,
  // временно наблюдалось до 5 слоёв (замерено skeptic Phase B) — визуального дефекта это не даёт:
  // нижний декодированный кадр виден сквозь ещё пустые верхние, а верхний слой всегда актуален.
  //
  // Ключ каждого слоя — САМА СЦЕНА (`scene-<id>`), и это принципиально. Первая редакция держала два
  // состояния (`outgoing`/`shown`) с ключами `outgoing-…`/`incoming-…`, и уходящий слой оказывался
  // НОВЫМ DOM-элементом: он стартовал пустым ровно так же, как приходящий, и удерживать ему было
  // нечего. Замер это и показал — 16 из 30 выборок без видимой сцены, то есть переход по-прежнему
  // шёл через пустоту. Со стабильным ключом React сохраняет уже отрисованный <img> предыдущей
  // сцены, и именно он закрывает окно, пока новая декодируется.
  const [layers, setLayers] = useState<OfficeSceneId[]>([sceneId]);
  // Предыдущее значение пропа. Ref обновляется ВНУТРИ эффекта, а не во время рендера: запись в ref
  // на этапе рендера ломает конкурентный рендеринг и запрещена правилом react-hooks/refs.
  const previousSceneIdRef = useRef(sceneId);

  useEffect(() => {
    if (previousSceneIdRef.current === sceneId) return;
    previousSceneIdRef.current = sceneId;
    setLayers((current) => {
      // Возврат к сцене, которая ещё в стеке (напр. пользователь передумал до загрузки новой):
      // её <img> уже смонтирован и декодирован, ждать нечего — схлопываем немедленно.
      // Без этой ветки стек оставался бы из двух слоёв НАВСЕГДА: `onReady` срабатывает не чаще
      // одного раза за монтирование, поэтому повторно поднятый наверх слой сигнал уже не пришлёт
      // (skeptic Phase B Step 16, NB-1 — воспроизведено на пути A → B(ещё грузится) → A).
      if (current.includes(sceneId)) return [sceneId];
      return [...current, sceneId];
    });
  }, [sceneId]);

  // Готовность верхнего слоя (успешная загрузка ЛИБО провал) — сигнал снять всё, что под ним.
  // Проверка «это всё ещё верхний слой» обязательна: при быстром переключении отделов сигнал может
  // прийти от сцены, которая к этому моменту уже не текущая, и без проверки она вытеснила бы собой
  // актуальную.
  const handleReady = (readyId: OfficeSceneId) => {
    setLayers((current) =>
      current.length > 1 && current[current.length - 1] === readyId ? [readyId] : current,
    );
  };

  return (
    <div className={styles.stack} aria-hidden="true" data-scene-crossfade={sceneId}>
      {layers.map((id, index) => {
        const isTop = index === layers.length - 1;
        return (
          <OfficeScenePhoto
            key={`scene-${id}`}
            sources={officeSceneById[id]}
            sizes={sizes}
            // Приближение играет только у верхнего слоя; нижние просто лежат под ним непрозрачными.
            className={`${photoClassName} ${isTop ? styles.layerIncoming : styles.layerOutgoing}`}
            onReady={isTop ? () => handleReady(id) : undefined}
          />
        );
      })}
    </div>
  );
}
