import { transaction } from "../db/client";
import { updateArticleCore, type ArticleInput, type ArticleRecord } from "./articles";
import {
  replaceRelationsFromCore,
  type ContentRelation,
  type ContentRelationInput,
} from "./contentRelations";

/**
 * Сохранение статьи вместе с её связями — ОДНОЙ транзакцией.
 *
 * Модуль существует ради одного свойства, которого нет ни у одного из двух репозиториев по
 * отдельности: правка текста статьи и замена её перелинковки либо применяются целиком, либо не
 * применяются вовсе. Порознь их вызвать можно и сегодня, но между двумя вызовами есть щель: отказ
 * на связях оставил бы уже сохранённый текст с прежним списком связей, а отказ на середине списка —
 * статью вообще без перелинковки.
 *
 * ЭТОТ МОДУЛЬ — ЕДИНСТВЕННЫЙ ВЛАДЕЛЕЦ ТРАНЗАКЦИИ в операции. Внутри вызываются только
 * transaction-neutral ядра (`updateArticleCore`, `replaceRelationsFromCore`), никогда их обёртки:
 * `transaction()` в проекте намеренно не реентерабельна, и вложенный `BEGIN` не просто падает —
 * его `ROLLBACK` отменяет ВНЕШНЮЮ транзакцию, после чего внешний `COMMIT` падает вторым,
 * бессмысленным сообщением. Проверка на это стоит отдельным тестом.
 *
 * Всё содержимое транзакции СИНХРОННО. `transaction()` не ждёт промисов: один `await` внутри
 * означал бы `COMMIT` до конца работы, то есть ровно ту потерю атомарности, ради которой модуль и
 * написан.
 *
 * Что здесь НЕ делается намеренно: `revalidateSection()`, IndexNow и любые другие внешние эффекты.
 * Они не откатываются вместе с транзакцией, поэтому их место — после успешного возврата, в роуте.
 *
 * `articles.related_slugs` эта операция не трогает: прежняя перелинковка статей живёт своей жизнью
 * до отдельного шага переноса.
 */

/**
 * Связи статьи после сохранения, ТРИ различимых состояния:
 *
 * | `relations`        | Что происходит                          |
 * | ------------------ | --------------------------------------- |
 * | `undefined`        | связи НЕ трогаются                      |
 * | `[]`               | все исходящие связи статьи удаляются    |
 * | непустой массив    | полная замена списка                    |
 *
 * Различие первых двух состояний — не педантизм: форма перелинковки появится отдельным шагом, и до
 * тех пор админ-панель шлёт `PUT` вообще без этого поля. Если бы «поле не прислано» означало
 * пустой список, каждое сохранение текста статьи молча стирало бы её связи. По той же причине в
 * схеме запроса у поля НЕТ `.default([])`.
 */
export interface UpdateArticleWithRelationsResult {
  article: ArticleRecord;
  /** Итоговые связи — только когда список менялся. `undefined` означает «не трогали». */
  relations?: ContentRelation[];
}

export function updateArticleWithRelations(
  id: string,
  input: ArticleInput,
  relations?: readonly ContentRelationInput[],
): UpdateArticleWithRelationsResult {
  return transaction(() => {
    const article = updateArticleCore(id, input);

    // Проверка на `undefined`, а не на длину: пустой массив — это явная очистка, и она обязана
    // дойти до `DELETE`.
    if (relations === undefined) return { article };

    return { article, relations: replaceRelationsFromCore("article", id, relations) };
  });
}
