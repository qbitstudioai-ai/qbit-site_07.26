/**
 * Константы авторизации без единой зависимости от Node API.
 *
 * Отдельный модуль нужен именно поэтому: их читает `src/middleware.ts`, который исполняется на Edge
 * — там нет ни `node:path`, ни файловой системы, и импорт `src/server/config.ts` уронил бы сборку.
 */

export const SESSION_COOKIE_NAME = "qbit_admin_session";

/** Время жизни сессии администратора — 8 часов. */
export const SESSION_TTL_MS = 8 * 60 * 60 * 1000;

/** Защита входа: не более 10 неудачных попыток с одного адреса за 15 минут. */
export const LOGIN_RATE_LIMIT = { maxAttempts: 10, windowMs: 15 * 60 * 1000 } as const;

/**
 * Общий предел неудачных попыток за то же окно — независимо от адреса.
 *
 * Нужен потому, что адресный счётчик опирается на `X-Forwarded-For`, а этот заголовок ставит
 * клиент. Даже при верно настроенном прокси распределённый подбор идёт с множества адресов, и
 * каждый из них остаётся ниже порога. Этот счётчик подделать нечем: он не зависит от заголовков.
 *
 * Порог заведомо выше любой нормальной работы (владелец сайта — один человек с одним паролем),
 * поэтому обычным использованием он не достигается. Осознанный компромисс: при массовом подборе
 * вход будет закрыт и для владельца, пока не истечёт окно. Неограниченный подбор пароля к
 * единственной учётной записи без второго фактора — риск заметно больший.
 */
export const LOGIN_GLOBAL_RATE_LIMIT = { maxAttempts: 100, windowMs: 15 * 60 * 1000 } as const;
