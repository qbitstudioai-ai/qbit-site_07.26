/**
 * Адрес клиента, которому можно верить.
 *
 * `X-Forwarded-For` и `X-Real-IP` ставит КЛИЕНТ, а не сеть. Node-сервер за обратным прокси не
 * может отличить заголовок, выставленный прокси, от заголовка, присланного из браузера, — если
 * прокси его не перезаписывает. Поэтому любое ограничение частоты, построенное на безусловном
 * чтении этих заголовков, обходится сменой значения на каждый запрос.
 *
 * Заголовки читаются, только когда администратор сервера явно подтвердил `TRUST_PROXY=1`, то есть
 * что приложение недоступно напрямую и прокси заголовок контролирует (см. PRE_RELEASE_CHECKLIST.md).
 *
 * Берётся ПОСЛЕДНИЙ элемент цепочки: первый прислал клиент, последний дописал ближайший прокси.
 * Верно для обеих типовых настроек nginx — `$proxy_add_x_forwarded_for` (дописывает в конец) и
 * `$remote_addr` (перезаписывает целиком, элемент остаётся один).
 *
 * `null` означает «адрес неизвестен»: вызывающий код обязан обработать это явно, а не подставлять
 * строку-заглушку, иначе все клиенты сольются в один счётчик и посторонний закроет доступ всем.
 */
export function trustedClientAddress(headers: Headers): string | null {
  if (process.env.TRUST_PROXY !== "1") return null;

  const forwarded = headers.get("x-forwarded-for");
  if (forwarded) {
    const chain = forwarded
      .split(",")
      .map((part) => part.trim())
      .filter(Boolean);
    if (chain.length > 0) return chain[chain.length - 1];
  }

  return headers.get("x-real-ip")?.trim() || null;
}
