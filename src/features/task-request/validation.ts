import { z } from "zod";

/**
 * Правила валидации заявки «Ваша задача» — ОДИН источник для клиента и сервера (Step 12.7).
 *
 * Разъезжающиеся правила — классический источник дефектов: форма пропускает то, что сервер режет,
 * или наоборот. Поэтому лимиты и схема лежат здесь и импортируются обеими сторонами. Модуль
 * намеренно не тянет ничего из React и Next — он должен одинаково работать в route handler,
 * в клиентском компоненте и в unit-тестах.
 */

/** Ниже этого порога сообщение бесполезно: «привет», «тест», случайное нажатие. */
export const TASK_MESSAGE_MIN_LENGTH = 20;

/**
 * Верхний предел. Telegram обрезает сообщения примерно на 4096 символах; берём заметно меньше,
 * чтобы вместе с подписью-обёрткой гарантированно уложиться и не отправлять обрезанное.
 */
export const TASK_MESSAGE_MAX_LENGTH = 3000;

export const taskRequestSchema = z.object({
  message: z.string().trim().min(TASK_MESSAGE_MIN_LENGTH).max(TASK_MESSAGE_MAX_LENGTH),
  /**
   * Honeypot: поле, спрятанное от людей и видимое ботам, которые заполняют всё подряд. Человек
   * оставляет его пустым.
   *
   * Схема принимает ЛЮБОЕ значение намеренно, хотя напрашивается `.max(0)`. Если бы схема
   * отвергала заполненный honeypot, роут отвечал бы «400 неверный запрос» — то есть прямо сообщал
   * боту, что его распознали, и подсказывал, какое поле не трогать в следующий раз. Решение о
   * тихом отбрасывании принимает роут, отвечая как при успехе (найдено unit-тестом: ветка отброса
   * была недостижима, потому что до неё не доходило).
   */
  website: z.string().optional(),
});

export type TaskRequest = z.infer<typeof taskRequestSchema>;

/** Достаточно ли содержательный текст, чтобы включать кнопку отправки. */
export function isSubmittableTaskMessage(message: string): boolean {
  const trimmed = message.trim();
  return trimmed.length >= TASK_MESSAGE_MIN_LENGTH && trimmed.length <= TASK_MESSAGE_MAX_LENGTH;
}
