import type { Department, TaskSectionCopy } from "@/content/types";
import { TASK_SECTION_ID, type OfficeSectionId } from "./reducer";
import { hotspotId, TASK_ENTRY_BUTTON_ID } from "./focusTargets";

/**
 * РЕЕСТР РАЗДЕЛОВ ОФИСА (Step 18, находка архитектора M7).
 *
 * Раздел офиса — это то, что занимает 90%-область и имеет пункт в рельсе. Сегодня их шесть: пять
 * отделов и «Ваша задача». До Step 18 знание о шестом было размазано по коду отдельными ветками:
 *   — OfficeExperience решал, что показать в 90%-области, и какая сцена лежит позади;
 *   — DepartmentNavigationRail дорисовывал ШЕСТОЙ пункт литералом, вручную повторяя разметку
 *     активного/неактивного состояния рядом с циклом по отделам;
 *   — focusTargets отдельной веткой знал, какой контрол overview открывает этот раздел.
 * То есть добавление раздела требовало согласованной правки в нескольких местах, и пропуск любой из
 * них давал МОЛЧАЛИВЫЙ дефект — ровно так Step 12.7 и сломал возврат фокуса, добавив шестой раздел
 * в механизм, рассчитанный на пять (разбор — в focusTargets.ts).
 *
 * Здесь это знание собрано в одном месте: описание раздела, а не набор условий про него.
 *
 * ГРАНИЦА, которую реестр НЕ переходит, и это осознанно. Он описывает данные раздела, но не его
 * содержимое: какой компонент рисует 90%-область, решает слой компонентов по полю `kind`. Класть
 * сюда React-компоненты значило бы затащить UI в слой машины состояний и сделать реестр
 * неимпортируемым из тестов машины.
 *
 * Что реестр даёт НА САМОМ ДЕЛЕ — формулировка уточнена после skeptic-ревью Step 18 (находка N1),
 * первая редакция этого комментария преувеличивала:
 *   — новый ОТДЕЛ добавляется данными (data/departments.json + data/office-zones.json) и кода не
 *     трогает. Но это было верно и ДО реестра: рельс и раньше шёл циклом по отделам. Этой половиной
 *     шаг ничего не добыл;
 *   — новый раздел ИНОГО рода — НЕ «одна запись здесь». Кроме записи правятся: тернарник выбора
 *     содержимого 90%-области в `OfficeExperience` (иначе седьмой раздел отрисуется формой «Ваша
 *     задача»), объединение `OfficeSectionKind`, проброс его копирайта, сам компонент содержимого,
 *     а также объединение `OfficeSectionId` в `reducer.ts` и разбор адреса в `url-sync` — без них
 *     раздел не будет ни типизирован, ни адресуем ссылкой (последние два дописаны по второму
 *     skeptic-ревью Step 18: первая редакция этого перечня их не считала).
 *
 * Настоящий выигрыш реестра — в другом, и он не про количество точек, а про их СОГЛАСОВАННОСТЬ:
 * знание «какой контрол открыл раздел» перестало существовать четвёртой копией в `focusTargets`
 * (именно её Step 12.7 забыл обновить, отправив фокус на <body>), а разметка пункта рельса
 * перестала дублироваться между циклом по отделам и литеральным шестым пунктом.
 */
export type OfficeSectionKind = "department" | "aside";

export interface OfficeSectionDescriptor {
  id: OfficeSectionId;
  /**
   * Род раздела. `department` — отдел офиса: своя сцена, миниатюра в рельсе, зона на карте.
   * `aside` — раздел, который отделом не является: сцены своей не имеет, зоны на карте тоже.
   */
  kind: OfficeSectionKind;
  /** Подпись пункта рельса. */
  railLabel: string;
  /**
   * id сцены офиса позади раздела. У отдела — своя, у остальных — мастер-сцена overview: офис как
   * общий контекст (Step 12.7). Тип строковый намеренно: реестр живёт в слое машины и не должен
   * зависеть от каталога изображений — соответствие id проверяется тестом.
   */
  sceneId: string;
  /**
   * id контрола на overview, который открывает раздел, — цель возврата фокуса при закрытии
   * (docs/11). У отдела это зона на сцене, у «Вашей задачи» — отдельная кнопка над сценой.
   */
  entryControlId: string;
}

/**
 * Собирает реестр в порядке рельса: сначала отделы (в порядке, заданном вызывающим — он совпадает с
 * порядком зон на карте), затем разделы иного рода.
 *
 * Порядок отделов НЕ пересортировывается здесь: он уже вычислен по officeZones и обязан совпадать
 * между картой overview и рельсом, иначе отделы «переезжают» при открытии раздела.
 */
export function buildOfficeSections(
  departments: Department[],
  taskCopy: TaskSectionCopy,
): OfficeSectionDescriptor[] {
  return [
    ...departments.map((department): OfficeSectionDescriptor => ({
      id: department.id,
      kind: "department",
      railLabel: department.overviewLabel,
      sceneId: department.id,
      entryControlId: hotspotId(department.id),
    })),
    {
      id: TASK_SECTION_ID,
      kind: "aside",
      railLabel: taskCopy.railLabel,
      // Не отдел — своей сцены не имеет, под ним остаётся мастер-сцена офиса (Step 12.7).
      sceneId: "overview",
      entryControlId: TASK_ENTRY_BUTTON_ID,
    },
  ];
}

/**
 * Кандидаты возврата фокуса после закрытия раздела, в порядке предпочтения (docs/11 «после закрытия
 * focus возвращается»).
 *
 * Возвращать фокус нужно на тот контрол, который раздел ОТКРЫЛ, иначе пользователь теряет место. У
 * отдела это зона на сцене, у «Вашей задачи» — отдельная кнопка над сценой; отсюда и берётся
 * `entryControlId`. До Step 18 эта функция жила в focusTargets.ts и различала два случая
 * СОБСТВЕННОЙ веткой — четвёртой копией знания о составе разделов, и именно её Step 12.7 забыл
 * обновить, из-за чего фокус уходил на <body>.
 *
 * Последним кандидатом всегда идёт карусель: она — единственная навигация, гарантированно
 * отрисованная на мобильном, и служит фолбэком, когда основной контрол не отрисован. Неизвестный
 * раздел (id, которого нет в реестре) вырождается в этот же фолбэк, а не остаётся без кандидатов
 * вовсе — фокус на <body> хуже, чем фокус не на том контроле.
 */
export function closeReturnCandidateIds(
  sections: OfficeSectionDescriptor[],
  returnSectionId: OfficeSectionId,
): readonly string[] {
  const section = sections.find((candidate) => candidate.id === returnSectionId);
  return section ? [section.entryControlId] : [];
}
