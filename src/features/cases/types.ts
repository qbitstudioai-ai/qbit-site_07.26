/**
 * Модель кейса раздела «Кейсы».
 *
 * Это КОНТРАКТ между источником данных и отображением, а не описание конкретных дел. Компоненты
 * раздела получают один объект `CaseStudy` и не знают ни сколько кейсов существует, ни откуда они
 * пришли — из файла (`casesRealData.ts` / `casesDraftData.ts`) или из будущей админ-панели. Поэтому
 * новый кейс, созданный владельцем сайта, автоматически получает и папку в картотеке, и досье, и
 * перелистывание, и печать: ничего «под конкретный кейс» в коде не зашито.
 *
 * Поля подобраны так, чтобы каждое имело однозначный столбец (или связанную таблицу) в будущей БД и
 * ни одно не требовало вычисления в компоненте. `fileNumber` не выводится из позиции в массиве
 * намеренно: номер дела в архиве должен пережить и переупорядочивание, и снятие кейса с публикации.
 */

/** Состояние публикации. См. правило видимости в `src/server/content/cases.ts`. */
export type CaseStatus = "draft" | "published";

/**
 * Измеримое изменение процесса: одна строка «до/после».
 *
 * `before`/`after` — строки, а не числа: у реальных замеров есть единица измерения и диапазон
 * («4–5 часов в неделю»), а форматировать их в компоненте значило бы зашить в код предположения о
 * том, что именно измерялось. `sourceNote` обязателен по смыслу, а не по типу: цифра без указания
 * источника — обещание, а не факт, и админ-панель должна иметь возможность его не заполнить только
 * там, где источник очевиден из текста.
 */
export interface CaseMetric {
  label: string;
  before: string;
  after: string;
  sourceNote?: string;
}

/**
 * Блок содержимого раздела досье.
 *
 * Раздел — это упорядоченная последовательность блоков, а не просто массив абзацев. Причина
 * практическая: в реальном кейсе цепочка процесса стоит СРАЗУ после вводящего её абзаца, а таблица
 * «до/после» — внутри «Результата», между абзацами. С плоским списком абзацев плюс отдельными
 * необязательными полями порядок пришлось бы зашивать в компонент, то есть в код — и первый же
 * кейс из админ-панели, где порядок другой, отрисовался бы неправильно.
 */
export type CaseBlock =
  | { kind: "text"; text: string }
  /** Цепочка шагов процесса. Отрисовывается семантическим списком, стрелки — оформление. */
  | { kind: "chain"; steps: string[] }
  /** Служебная таблица измеримых изменений. */
  | { kind: "metrics"; items: CaseMetric[] };

/** Раздел досье: заголовок и блоки содержимого. */
export interface CaseSection {
  /** Стабильный якорь. Годится для `id` заголовка и будущих ссылок внутрь документа. */
  id: string;
  heading: string;
  blocks: CaseBlock[];
}

/**
 * Спокойная ссылка в конце досье.
 *
 * НЕОБЯЗАТЕЛЬНА и намеренно устроена как данные, а не как элемент вёрстки: у архивного документа
 * это одна строка, а не рекламный блок, и следующий кейс из админ-панели может её не иметь вовсе.
 * Никакой связи с конкретным продуктом здесь нет — только адрес, который автор кейса указал сам.
 */
export interface CaseCallToAction {
  label: string;
  href: string;
}

export interface CaseStudy {
  id: string;
  /** Часть адреса `/cases/[slug]`. Стабилен: адрес опубликованного кейса не меняется. */
  slug: string;
  /** Заголовок документа. Ровно один H1 на страницу кейса. */
  title: string;
  /** Короткое имя на корешке папки в картотеке. */
  shortTitle: string;
  /** Мелкая служебная подпись над именем папки. */
  folderCaption: string;
  /** Номер дела в архиве. Строка, а не число: ведущий ноль — часть номера. */
  fileNumber: string;
  /** Служебная метка в шапке документа. */
  label: string;
  /**
   * Короткая строка под заголовком и описание страницы для метаданных.
   *
   * НЕОБЯЗАТЕЛЬНА. У реального кейса собственного вводного предложения нет: документ открывается
   * разделом «Краткий итог», и повторять его строкой выше значило бы продублировать текст в HTML.
   * Когда поля нет, описание страницы берётся из первого текстового блока досье.
   */
  summary?: string;
  sections: CaseSection[];
  /**
   * Спокойная ссылка в конце документа. Нет поля — нет ссылки; заготовки её не имеют.
   */
  cta?: CaseCallToAction;
  /**
   * Заголовок страницы для поисковой выдачи. Берётся ДОСЛОВНО — бренд к нему не дописывается
   * (см. `normalizeSeoTitle` в `src/lib/seo.ts`): владелец сайта пишет заголовок целиком, и
   * автоматическая приписка означала бы, что сохранённая строка и строка в выдаче различаются.
   * H1 документа при этом остаётся другим: у него своя задача — заголовок дела, а не выдачи.
   */
  seoTitle?: string;
  /** Описание страницы. Когда не заполнено, берётся `summary`, а затем первый абзац досье. */
  seoDescription?: string;
  /**
   * Описание для соцсетей и мессенджеров, если оно должно отличаться от `seoDescription`.
   *
   * Поле существует не ради разнообразия: описание в выдаче отвечает на запрос и потому держит
   * цифры, а карточка в мессенджере читается без запроса и должна быть понятна сама по себе.
   * Не заполнено — Open Graph берёт `seoDescription`, и никакого расхождения не возникает.
   */
  ogDescription?: string;
  /**
   * Дата первой публикации кейса и дата последнего изменения — ISO 8601.
   *
   * ОБА поля необязательны и заполняются ТОЛЬКО подтверждённой датой. Дата сборки, системное
   * «сегодня», дата коммита и время правки файла на эту роль не годятся: они рассказывают о
   * репозитории, а не о материале. Пока подтверждённой даты нет, поля остаются `undefined` — и
   * тогда у кейса нет ни `Article`-разметки, ни `lastmod` в карте сайта. Так же устроена карта
   * сайта в целом (`src/app/sitemap.ts`) и по той же причине.
   */
  publishedAt?: string;
  modifiedAt?: string;
  status: CaseStatus;
  /** Ставить ли печать на документ. Переключатель будущей админ-панели, не константа кода. */
  stampEnabled: boolean;
  /** Порядок в картотеке. Меньшее значение — выше. */
  sortOrder: number;
}

/** Первый текстовый блок досье. Он же — запасное описание страницы, когда `summary` не заполнен. */
export function firstTextBlock(study: CaseStudy): string | undefined {
  for (const section of study.sections) {
    for (const block of section.blocks) {
      if (block.kind === "text") return block.text;
    }
  }

  return undefined;
}
