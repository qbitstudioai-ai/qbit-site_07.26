/**
 * Предложение адреса страницы по её названию.
 *
 * ПРЕДЛОЖЕНИЕ, а не правило: значение подставляется в поле, пока владелец сайта не правил его сам,
 * и остаётся полностью редактируемым до публикации. Автоматический адрес нужен ровно затем, чтобы
 * человек, пишущий кейс, не изобретал латиницу вручную и не оставлял в адресе пробелы.
 *
 * Таблица — практическая транслитерация, а не ГОСТ: адрес читают люди и поисковые системы, и
 * «щ» → `shch` привычнее, чем `ŝ`. Мягкий и твёрдый знаки исчезают: в адресе им соответствовать
 * нечему.
 *
 * Модуль ЧИСТЫЙ и не знает ни про формы, ни про базу — его же проверяет unit-тест.
 */

const TRANSLITERATION: Record<string, string> = {
  а: "a",
  б: "b",
  в: "v",
  г: "g",
  д: "d",
  е: "e",
  ё: "e",
  ж: "zh",
  з: "z",
  и: "i",
  й: "y",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  п: "p",
  р: "r",
  с: "s",
  т: "t",
  у: "u",
  ф: "f",
  х: "h",
  ц: "ts",
  ч: "ch",
  ш: "sh",
  щ: "shch",
  ъ: "",
  ы: "y",
  ь: "",
  э: "e",
  ю: "yu",
  я: "ya",
};

/**
 * Название → адрес: строчные латинские буквы, цифры и дефис.
 *
 * Результат совместим с проверкой `slugSchema` на сервере (`^[a-z0-9]+(?:-[a-z0-9]+)*$`) либо пуст:
 * из названия, целиком состоящего из знаков препинания, адреса не получится, и подставлять туда
 * что-либо выдуманное нельзя — поле остаётся пустым, и человек заполняет его сам.
 */
export function slugFromTitle(title: string): string {
  const latin = title
    .toLowerCase()
    .split("")
    .map((character) => TRANSLITERATION[character] ?? character)
    .join("");

  return (
    latin
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 120)
      // Обрезка по длине могла оставить дефис на конце — адрес с висящим дефисом схему не проходит.
      .replace(/-+$/g, "")
  );
}
