/**
 * Общий словарь связей для админ-панели: типы, пределы и приведение ответа сервера к значению формы.
 *
 * ОТДЕЛЬНЫЙ МОДУЛЬ БЕЗ `"use client"`, и это не вкусовщина. Каталог материалов собирает серверный
 * компонент `/admin/blog`, а пользуется им клиентский `RelationEditor`. Если бы функция приведения
 * жила в клиентском модуле, серверный компонент импортировал бы не её, а ссылку на клиентский
 * модуль: типы стёрлись бы при компиляции и ничего не сломали, а вызов на сервере упал бы уже во
 * время запроса — то есть мимо сборки, тестов и любого статического анализа. Нейтральный модуль
 * снимает этот класс отказа целиком.
 */

export type RelationEntityType = "article" | "product" | "case" | "department";

/**
 * Одна связь в значении формы.
 *
 * Ровно два поля, и это существенно: `role` и `sortOrder` физически невозможно отправить, а не
 * «принято не отправлять». Порядок передаётся положением элемента в массиве.
 */
export interface ArticleRelationValue {
  targetType: RelationEntityType;
  targetId: string;
}

/**
 * Строка связи в том виде, в каком её отдаёт сервер: с ролью, порядком и отметками времени.
 *
 * Здесь описаны только те поля, которые действительно нужны клиенту. Остальные приходят и
 * отбрасываются.
 */
export interface RelationTargetShape {
  targetType: RelationEntityType;
  targetId: string;
}

/**
 * Материал, доступный для выбора целью.
 *
 * Собирается на сервере (`/admin/blog`) и приходит готовым: клиенту незачем ходить за каталогами
 * отдельными запросами, а первый экран не должен начинаться со скелетона.
 */
export interface RelationOption {
  type: RelationEntityType;
  id: string;
  label: string;
  /** Уточнение под названием: адрес материала или пояснение, почему он недоступен. */
  detail: string;
  isPublished: boolean;
  /** Раздел сайта. Есть только у статей — у остальных типов раздела не существует. */
  placement: string | null;
}

/**
 * Пределы списка.
 *
 * Оба проверяются на сервере независимо от формы; здесь они нужны, чтобы кнопка «Добавить» гасла
 * до отправки, а не после отказа. Числа продублированы, потому что серверные модули тянут за собой
 * доступ к базе и в клиентский бандл им нельзя; совпадение с сервером закреплено отдельным тестом.
 */
export const MAX_ARTICLE_TARGETS = 6;
export const MAX_RELATIONS = 24;

/**
 * Ответ сервера → значение формы.
 *
 * Лишние поля отбрасываются НАМЕРЕННО, а не по невнимательности. Схема запроса принимает и `role`,
 * и `sortOrder`; если бы пришедшая с сервера строка попадала в значение формы целиком, следующее
 * сохранение вернуло бы их обратно — то есть форма начала бы диктовать роль и числовой порядок,
 * которых человек не задавал. Порядок обязан оставаться одним: положением в списке.
 */
export function toRelationValues(
  relations: readonly RelationTargetShape[],
): ArticleRelationValue[] {
  return relations.map((relation) => ({
    targetType: relation.targetType,
    targetId: relation.targetId,
  }));
}
