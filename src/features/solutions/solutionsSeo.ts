import type { Metadata } from "next";
import type { Department } from "@/content/types";
import { breadcrumbNode, organizationNode, SITE_NAME, SITE_URL, webPageNode } from "@/lib/seo";
import { solutionUrl } from "./solutionsRoutes";

/**
 * SEO страниц отделов.
 *
 * Весь ВИДИМЫЙ и весь ОПИСАТЕЛЬНЫЙ текст страницы приходит из самого отдела. Единственная строка,
 * которой в данных отдела нет, — общая часть заголовка выдачи (см. `solutionSeoTitle`); она
 * утверждена руководителем формулой и одинакова у всех пяти страниц, то есть не является ни
 * обещанием, ни описанием конкретного отдела.
 *
 * Разметка собирается ТЕМИ ЖЕ helper'ами, что и на остальных страницах сайта (`breadcrumbNode`,
 * `webPageNode`, `organizationNode`), поэтому организация и сайт остаются ОДНОЙ сущностью графа:
 * общие `@id` здесь не переопределяются ни разу.
 */

/**
 * Robots для несуществующего отдела.
 *
 * Страница в этом случае вызывает `notFound()`, и Next.js добавляет к ней собственный `noindex`;
 * это значение существует ради `generateMetadata`, который исполняется раньше и обязан вернуть
 * что-то определённое. `follow: true` — ссылки в шапке настоящие, закрывать обход незачем.
 * Значение своё, а не импортированное из раздела «Кейсы»: тянуть в отделы весь модуль кейсов ради
 * двух полей значило бы связать два независимых раздела на пустом месте.
 */
export const NOT_FOUND_ROBOTS = {
  index: false,
  follow: true,
} as const satisfies Metadata["robots"];

/**
 * Общая часть заголовка выдачи.
 *
 * Вынесена константой, потому что её проверяет тест: строка обязана быть ОДНОЙ на все пять
 * страниц. Если она когда-нибудь начнёт различаться по отделам, это будет уже описание отдела —
 * то есть новый маркетинговый текст, которого в этом шаге быть не должно.
 */
export const SOLUTION_TITLE_SUBJECT = "автоматизация бизнес-процессов";

/**
 * Заголовок страницы отдела для поисковой выдачи.
 *
 * Формула утверждена руководителем: `«<Отдел>: автоматизация бизнес-процессов — <бренд>»`.
 *
 * Почему не `withBrand(department.name)`. Одно название отдела в выдаче не отвечает ни на один
 * запрос: «HR — QBit-Studio-Ai» и «Дирекция — QBit-Studio-Ai» вне контекста нечитаемы, а запрос
 * «автоматизация отдела продаж», ради которого страница и создаётся, в такой строке не выражен
 * вовсе. Общая часть добавляет предмет страницы, не обещая ничего сверх того, что на ней написано.
 *
 * Бренд приписан здесь же, а не через `withBrand`: формула задана целиком, и повторная приписка
 * дала бы двойное название компании.
 */
export function solutionSeoTitle(department: Pick<Department, "name">): string {
  return `${department.name}: ${SOLUTION_TITLE_SUBJECT} — ${SITE_NAME}`;
}

/**
 * Описание страницы отдела.
 *
 * ДОСЛОВНО `department.problem` — тот самый абзац, который стоит на странице под заголовком. Так
 * сниппет в выдаче и содержимое страницы не могут разойтись: правка текста в админ-панели меняет
 * и то, и другое одной операцией. Ни обрезки, ни перефразирования здесь нет и быть не должно.
 */
export function solutionSeoDescription(department: Pick<Department, "problem">): string {
  return department.problem;
}

/**
 * Разметка страницы отдела: BreadcrumbList → WebPage → Organization.
 *
 * Чего здесь НЕТ и не должно появиться:
 *
 * - `Service` и `Offer` — у отдела нет ни подтверждённой цены, ни состава работ, ни условий; это
 *   заявление о коммерческом предложении, которого на странице не существует;
 * - `FAQPage` — пары «боль → выгода» не являются вопросами и ответами;
 * - `HowTo` — `howItWorks` описывает внутреннюю цепочку системы, а не инструкцию для читателя;
 * - `Review`/`AggregateRating` — отзывов и оценок нет;
 * - `datePublished`/`dateModified` — подтверждённой даты публикации отдела не существует, а
 *   `updated_at` у неправленой записи равен моменту `db:seed` (разбор — в
 *   `src/server/content/lastModified.ts`). В карте сайта такая дата допустима с оговоркой, в
 *   разметке страницы она читалась бы как дата обновления документа, то есть как выдуманный факт.
 *
 * «Хлебные крошки» — ровно две ступени: «Главная» → название отдела. Промежуточной страницы
 * `/solutions` не существует, и создавать её ради третьей ступени нельзя: крошки описывают ту
 * вложенность, которая УЖЕ выражена структурой адресов, а ступень с адресом несуществующей
 * страницы была бы заявлением о несуществующем документе.
 */
export function solutionStructuredData(department: Department) {
  // Адрес берётся `solutionUrl()`, а не собирается строкой: canonical, Open Graph и разметка
  // обязаны говорить об одном и том же адресе, и одна точка сборки это гарантирует.
  const url = solutionUrl(department);

  return [
    breadcrumbNode([
      { name: "Главная", url: SITE_URL },
      { name: department.name, url },
    ]),
    webPageNode({
      url,
      name: solutionSeoTitle(department),
      description: solutionSeoDescription(department),
    }),
    organizationNode(),
  ];
}
