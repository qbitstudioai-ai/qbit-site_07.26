/**
 * Адреса страниц раздела «Решения» — по одному на отдел.
 *
 * Таблица вынесена в ОТДЕЛЬНЫЙ модуль без единой зависимости намеренно. Её читают два разных
 * рантайма:
 *
 * 1. приложение — через `@/content/schema`, который её реэкспортирует и сверяет с ней
 *    `solutionPath` каждого отдела при чтении из базы;
 * 2. `scripts/indexnow-submit-current.mjs` — обычным Node без сборщика.
 *
 * Пока таблица лежала в `schema.ts`, второй случай был невозможен: `schema.ts` импортирует `zod`,
 * которого нет в рабочем образе (`.next/standalone` тянет только оттрассированные зависимости
 * сервера), а алиасы `@/*` обычный Node не резолвит. Копия пяти адресов в скрипте означала бы
 * второй источник истины — ровно то, от чего защищает `superRefine` в схеме, только в другом месте.
 *
 * Отсюда правило: в этом файле не должно появиться НИ ОДНОГО импорта значения. Единственный
 * допустимый импорт — `import type`, который Node стирает вместе с остальными аннотациями.
 *
 * Отдельно про `executive`. Системный идентификатор отдела — `executive`, а сегмент адреса —
 * `management`. Это не опечатка: идентификатор — первичный ключ, к которому привязаны зона офиса,
 * сцена и связи материалов, а сегмент адреса — публичное слово. Подробности — в
 * `src/features/solutions/solutionsRoutes.ts`.
 */
