import type { HeroLink } from "./types";

/**
 * Пункт общей шапки «Найти потери» — вход в интерактивную карту офиса.
 *
 * Точка входа в офис до сих пор была одна: контурная кнопка «Найти потери в своём отделе» в hero
 * главной страницы. С внутренних страниц (`/blog`, `/products`, `/faq`, …) попасть в карту можно
 * было только вернувшись на главную и найдя кнопку глазами. Пункт меню делает этот путь явным и
 * одинаковым на всех страницах.
 *
 * Модуль ЧИСТЫЙ (только константы, без zod и доступа к базе) — его импортирует "use client"
 * Header, поэтому ничего серверного здесь быть не должно.
 */

/**
 * Значение `?section=`, означающее «показать карту офиса, отдел не выбран».
 *
 * `src/app/page.tsx` раскрывает офис при ЛЮБОМ `?section=` (`initialRevealed`), а конкретный раздел
 * открывает только для `?section=task`. Значение `office` попадает ровно в эту ветку: hero
 * пропускается, машина стартует в `overview`. Отдельного разбора в `page.tsx` оно не требует —
 * константа существует, чтобы адрес не был написан строкой в трёх местах.
 *
 * После монтирования `useDepartmentUrlSync` вычищает параметр (в `overview` активного раздела нет),
 * и в адресной строке остаётся `/`. Это совпадает с поведением кнопки в hero: состояние `overview`
 * своего адреса не имеет и никогда не имело.
 */
export const OFFICE_MAP_SECTION = "office";

/**
 * Адрес пункта. В новой вкладке и с внутренних страниц открывает главную сразу на карте офиса.
 *
 * Без JS карта отделов в первом серверном HTML тоже присутствует, но hero при этом остаётся
 * видимым: его скрывает правило `:global(.js) .heroGridHidden` (`OfficeMachine.module.css`). Это
 * унаследованное поведение, общее для `?section=task` и `?department=…`, — не особенность этого
 * пункта.
 */
export const OFFICE_MAP_HREF = `/?section=${OFFICE_MAP_SECTION}`;

/** Готовый пункт меню. Встраивается в `heroLinks` сразу после «Главной» (см. `server/content/homepage.ts`). */
export const OFFICE_MAP_LINK: HeroLink = {
  label: "Найти потери",
  href: OFFICE_MAP_HREF,
};
