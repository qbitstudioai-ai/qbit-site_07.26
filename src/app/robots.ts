import type { MetadataRoute } from "next";
import { SITE_URL } from "@/lib/seo";

export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      // Явное разрешение на весь публичный сайт. Ни CSS, ни JavaScript, ни изображения не
      // закрыты: поисковой системе нужен доступ к ним, чтобы отрисовать страницу так же, как её
      // видит посетитель. Закрытые ресурсы — классическая причина «страница выглядит пустой».
      allow: "/",
      disallow: [
        // `/api/` закрыт от обхода намеренно. Индексировать там нечего (JSON и файлы хранилища), а
        // попадание ссылок на `/api/files/*` в поисковый кэш означает, что снятый с публикации
        // документ продолжает выдаваться третьими сторонами.
        "/api/",
        // БЕЗ завершающего слэша: правило `/admin/` не покрывает сам адрес `/admin`. Директива
        // работает как префикс, поэтому `/admin` закрывает и раздел, и все вложенные страницы.
        // Второй рубеж — `noindex` в `src/app/admin/layout.tsx`: robots.txt не средство защиты.
        "/admin",
        "/login",
      ],
    },
    sitemap: `${SITE_URL}/sitemap.xml`,
    // `Host` — устаревшая директива Яндекса (отменена в 2018 году) и никогда не поддерживалась
    // Google. Оставлена как безвредная подсказка о предпочтительном зеркале; настоящий выбор
    // основного адреса делают canonical и серверная переадресация, см. SEO_GEO_AUDIT.md.
    host: SITE_URL,
  };
}
