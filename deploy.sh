#!/usr/bin/env bash
#
# Обновление сайта Allqbit на сервере. Запускается на самом сервере из /opt/allqbit:
#
#     cd /opt/allqbit && ./deploy.sh
#
# Что делает: забирает свежий код, пересобирает образ, прогоняет миграции базы и перезапускает
# контейнер. Данные админ-панели (тексты, документы) живут в /opt/allqbit-data и не затрагиваются.
#
# Первичная установка — не отсюда, а из DEPLOY.md: там создаются каталоги и файл секретов.

set -euo pipefail

DATA_DIR="/opt/allqbit-data"
ENV_FILE="${DATA_DIR}/production.env"
APP_UID=1001

cd "$(dirname "$0")"

say() { printf '\n\033[1m==> %s\033[0m\n' "$1"; }
die() { printf '\n\033[1;31mОшибка: %s\033[0m\n' "$1" >&2; exit 1; }

# ─── Проверки до того, как что-то менять ───────────────────────────────────────────────────────
#
# Дешевле упасть здесь, чем на середине деплоя с уже погашенным сайтом.

[ -f "$ENV_FILE" ] || die "нет файла секретов ${ENV_FILE}. Первичная установка описана в DEPLOY.md."

for var in ADMIN_LOGIN ADMIN_PASSWORD_HASH SESSION_SECRET; do
  grep -qE "^${var}=.+" "$ENV_FILE" || die "в ${ENV_FILE} не заполнена переменная ${var}."
done

docker network inspect supabase_default >/dev/null 2>&1 \
  || die "нет docker-сети supabase_default — через неё сайт соединяется с Caddy."

# ─── Код ───────────────────────────────────────────────────────────────────────────────────────

say "Забираю свежий код"
git fetch --prune origin
git reset --hard origin/master
git log -1 --format='Текущая версия: %h — %s'

# ─── Права на каталог данных ───────────────────────────────────────────────────────────────────
#
# Контейнер работает под UID 1001. Без этого шага SQLite получит «readonly database»: каталог,
# созданный root-ом, для него закрыт на запись.

say "Проверяю каталог данных"
mkdir -p "${DATA_DIR}/var/uploads"
chown -R "${APP_UID}:${APP_UID}" "${DATA_DIR}/var"
chmod 600 "$ENV_FILE"

# ─── Сборка ────────────────────────────────────────────────────────────────────────────────────
#
# Собирается ДО остановки старого контейнера: если сборка упадёт, работающий сайт не пострадает.

say "Собираю образ"
docker compose build

# ─── Миграции ──────────────────────────────────────────────────────────────────────────────────
#
# Отдельной одноразовой командой на новом образе, до подмены контейнера. `run --rm` не трогает
# работающий сайт. Флага --reset здесь нет и быть не должно: он очищает контентные таблицы.

say "Обновляю схему базы"
docker compose run --rm --no-deps allqbit-site node scripts/db-migrate.mjs

# ─── Запуск ────────────────────────────────────────────────────────────────────────────────────

say "Перезапускаю сайт"
docker compose up -d --force-recreate

# ─── Проверка ──────────────────────────────────────────────────────────────────────────────────
#
# Деплой не считается удачным, пока сайт не ответил. Ждём до минуты: standalone-серверу нужны
# секунды на старт, но на нагруженной машине это может занять дольше.

say "Жду ответа сайта"
for attempt in $(seq 1 30); do
  if docker compose exec -T allqbit-site wget --quiet --tries=1 --spider http://127.0.0.1:3000/ 2>/dev/null; then
    printf 'Сайт отвечает (попытка %s).\n' "$attempt"
    say "Готово"
    docker compose ps
    exit 0
  fi
  sleep 2
done

printf '\n\033[1;31mСайт не ответил за 60 секунд. Последние строки журнала:\033[0m\n' >&2
docker compose logs --tail 50 allqbit-site >&2
exit 1
