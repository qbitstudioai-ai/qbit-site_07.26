import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const inputPath = process.argv[2];
const articleConfig = [
  { slug: "kak-avtomatizirovat-obrabotku-zayavok" },
  { slug: "ai-assistent-po-baze-znaniy" },
  { slug: "analiz-zvonkov-otdela-prodazh" },
  { slug: "avtomatizatsiya-dokumentov-s-ai" },
  { slug: "sayt-crm-i-messendzhery" },
  { slug: "chto-mozhno-avtomatizirovat-na-n8n" },
];

const outputDirectory = path.resolve("src/content/blog");
await mkdir(outputDirectory, { recursive: true });

let articleSources;

if (inputPath) {
  const source = (await readFile(inputPath, "utf8")).replace(/\r\n/g, "\n");
  const headingPattern = /^# (\d+)\. (.+)$/gm;
  const headings = [...source.matchAll(headingPattern)];

  if (headings.length !== articleConfig.length) {
    throw new Error(`Expected 6 articles, found ${headings.length}`);
  }

  articleSources = headings.map((heading, index) => {
    const nextHeading = headings[index + 1];
    return source
      .slice(heading.index, nextHeading ? nextHeading.index : source.length)
      .replace(/\n---\s*$/u, "")
      .replace(/\s+$/u, "")
      .concat("\n");
  });

  await Promise.all(
    articleSources.map((articleSource, index) =>
      writeFile(
        path.join(outputDirectory, `${articleConfig[index].slug}.md`),
        articleSource,
        "utf8",
      ),
    ),
  );
} else {
  articleSources = await Promise.all(
    articleConfig.map(({ slug }) =>
      readFile(path.join(outputDirectory, `${slug}.md`), "utf8").then((source) =>
        source.replace(/\r\n/g, "\n"),
      ),
    ),
  );
}

const generated = articleSources.map((articleSource, index) => {
  const fileName = `${articleConfig[index].slug}.md`;
  return {
    slug: articleConfig[index].slug,
    sourceFile: fileName,
    sha256: createHash("sha256").update(articleSource).digest("hex"),
    markdown: articleSource,
  };
});

const generatedSource = `// Generated by scripts/import-blog-research.mjs.
// The Markdown files in src/content/blog are the canonical, human-readable source.

export const importedBlogArticles = ${JSON.stringify(generated, null, 2)} as const;
`;

await writeFile(path.resolve("src/features/blog/articles.generated.ts"), generatedSource, "utf8");

console.log(
  inputPath
    ? `Imported ${generated.length} articles from ${inputPath}`
    : `Regenerated ${generated.length} articles from canonical Markdown`,
);
